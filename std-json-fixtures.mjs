#!/usr/bin/env node
/**
 * Generates, guards and proves the CCT verification fixtures.
 *
 *   node ./std-json-fixtures.mjs --write      regenerate the fixtures (the generator)
 *   node ./std-json-fixtures.mjs              check the checked-in fixtures match (the drift guard)
 *   node ./std-json-fixtures.mjs --compile    recompile with solc and compare to vendored bytecode
 *
 * Generating and checking share one code path, which is what makes the guard trustworthy: the
 * check re-runs the assembler and diffs against what is on disk, so a hand-edited fixture, a
 * `@chainlink/contracts-ccip` bump, or an assembler change all fail loudly.
 *
 * This is the ONLY drift guard. `npm run generate:lint` cannot serve — `generate.cjs` exits 0 both
 * when a generator throws and when prettier fails to parse the file it just spliced.
 */

import { createRequire } from 'node:module'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { TARGETS, assembleAll } = require('./assemble-std-json.cjs')
const prettier = require('prettier')

const REPO = dirname(fileURLToPath(import.meta.url))
const FIXTURES = join(REPO, 'ccip-sdk/src/cct/evm/verify/fixtures/V2_0_0')
const PKG = join(REPO, 'node_modules/@chainlink/contracts-ccip')

const mode = process.argv.includes('--write')
  ? 'write'
  : process.argv.includes('--compile')
    ? 'compile'
    : 'check'

const HEADER = `/**
 * GENERATED by \`npm run generate:fixtures\` — do not edit.
 *
 * Assembled from the pinned \`@chainlink/contracts-ccip\` devDependency, so these fixtures are
 * co-versioned with the creation bytecode vendored in \`../../../artifacts/bytecode/\`. Verified
 * by \`npm run check:fixtures\` (wired into \`npm run check\`) and, at the bytecode level, by
 * \`npm run check:fixtures:bytecode\`.
 */`

/** Renders the deduplicated source pool module. */
function renderSources(assembled) {
  const payload = JSON.stringify(Object.fromEntries([...assembled.pool.entries()].sort()))
  return `${HEADER}

/**
 * Every unique Solidity source unit across all deployable contracts' import closures, keyed by
 * solc source-unit name. Deduplicated: a unit shared by several contracts is stored once. Never
 * share this pool across version directories — see the collision check in \`assemble-std-json.cjs\`.
 */
const sources = JSON.parse(${JSON.stringify(payload)}) as Record<string, string>

export default sources
`
}

/** Renders the per-contract manifest module. */
function renderManifest(assembled) {
  const { contracts, ...meta } = assembled
  const body = {
    contractsCcipVersion: meta.contractsCcipVersion,
    compilerVersion: meta.compilerVersion,
    evmVersion: meta.evmVersion,
    viaIR: meta.viaIR,
    bytecodeHash: meta.bytecodeHash,
    outputSelection: meta.outputSelection,
    contracts,
  }
  return `${HEADER}

import type { DeployableContract } from '../../../deployable.ts'
import type { FixtureEntry, FixtureManifest } from '../types.ts'

const manifest = ${JSON.stringify(body)} satisfies FixtureManifest & {
  contracts: Record<DeployableContract, FixtureEntry>
}

export default manifest
`
}

/** Formats generated source the way the repo's prettier config would, so lint stays quiet. */
async function format(source, filepath) {
  const options = await prettier.resolveConfig(filepath)
  return prettier.format(source, { ...options, filepath })
}

/**
 * Recompiles each fixture and asserts the bytecode matches the vendored `.bin` exactly.
 *
 * Imports the SHIPPED loader — not a re-implementation of it — so this proves the exact
 * Standard-JSON that `verifyDeployedContract` submits reproduces the deployed bytecode. Compiling
 * a locally-rebuilt twin would leave every compiler setting in the loader unguarded.
 */
async function compileAndCompare() {
  const solc = require('solc')
  const { loadStandardJson } = await import('./ccip-sdk/src/cct/evm/verify/fixtures/index.ts')
  let failures = 0
  console.log(`solc ${solc.version()}`)
  for (const [name, target] of Object.entries(TARGETS)) {
    const { input } = await loadStandardJson(name)
    const started = Date.now()
    const out = JSON.parse(solc.compile(JSON.stringify(input)))
    const errors = (out.errors ?? []).filter((e) => e.severity === 'error')
    if (errors.length) {
      console.error(`✗ ${name}: ${errors[0].formattedMessage.split('\n')[0]}`)
      failures++
      continue
    }
    const got = out.contracts?.[target.unit]?.[name]?.evm?.bytecode?.object
    const want = readFileSync(join(PKG, 'bytecode/v2_0_0', target.bin), 'utf8')
      .trim()
      .replace(/^0x/, '')
    if (got !== want) {
      console.error(`✗ ${name}: bytecode differs (got ${got?.length}, want ${want.length} chars)`)
      failures++
      continue
    }
    console.log(`✓ ${name} (${input.settings.optimizer.runs} runs, ${Date.now() - started} ms)`)
  }
  return failures
}

const assembled = assembleAll()
const files = [
  ['sources.ts', renderSources(assembled)],
  ['manifest.ts', renderManifest(assembled)],
]

if (mode === 'write') {
  mkdirSync(FIXTURES, { recursive: true })
  for (const [name, source] of files) {
    const path = join(FIXTURES, name)
    writeFileSync(path, await format(source, path))
    console.log(`wrote ${path}`)
  }
} else if (mode === 'check') {
  let drift = 0
  for (const [name, source] of files) {
    const path = join(FIXTURES, name)
    const expected = await format(source, path)
    let actual
    try {
      actual = readFileSync(path, 'utf8')
    } catch {
      console.error(`✗ ${name} is missing — run \`npm run generate:fixtures\``)
      drift++
      continue
    }
    if (actual !== expected) {
      console.error(`✗ ${name} is stale — run \`npm run generate:fixtures\``)
      drift++
    }
  }
  if (drift) process.exit(1)
  console.log(
    `✓ verification fixtures match @chainlink/contracts-ccip@${assembled.contractsCcipVersion}`,
  )
} else {
  if (await compileAndCompare()) process.exit(1)
  console.log('✓ all fixtures recompile to the vendored creation bytecode')
}
